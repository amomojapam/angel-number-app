// ---------------------------------------------------------------
// 3) 数字とテーマから、決まったカードを選ぶための簡易ハッシュ
//    同じ「数字 × テーマ」なら、いつも同じカードが選ばれます。
// ---------------------------------------------------------------
function hashToIndex(str, mod) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }
  return hash % mod;
}

function pickCardId(number, themeId) {
  const index = hashToIndex(`${number}_${themeId}_card`, CARDS.length);
  return CARDS[index].id;
}

function pickVariant(list, seedKey) {
  return list[hashToIndex(seedKey, list.length)];
}

function pickAdvice(pool, seedKey, count = 3) {
  const startIndex = hashToIndex(seedKey, pool.length);
  const result = [];
  for (let i = 0; i < count; i++) {
    result.push(pool[(startIndex + i) % pool.length]);
  }
  return result;
}

// ---------------------------------------------------------------
// 4) メインの関数：数字とテーマから診断結果を組み立てる
// ---------------------------------------------------------------
function getReading(number, themeId) {
  const theme = getThemeById(themeId);
  if (!theme) return null;

  const overrideKey = `${number}_${themeId}`;
  const override = READING_OVERRIDES[overrideKey];

  const cardId = override?.cardId ?? pickCardId(number, themeId);
  const card = getCardById(cardId);
  const content = THEME_CONTENT[themeId];

  const summary = override?.summary ?? card.coreMeaning;

  const message =
    override?.message ??
    [
      `${pickVariant(content.opening, `${number}_${themeId}_open`)}`,
      `${pickVariant(content.reflection, `${number}_${themeId}_reflect`)}`,
    ];

  const advice =
    override?.advice ?? pickAdvice(content.advicePool, `${number}_${themeId}_advice`, 3);

  const todayWord =
    override?.todayWord ?? pickVariant(TODAY_WORDS, `${number}_${themeId}_today`);

  return {
    number,
    theme,
    card,
    summary,
    message,
    advice,
    todayWord,
  };
}

return { getReading, READING_OVERRIDES };
